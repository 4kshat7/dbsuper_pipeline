#!/usr/bin/env bash
# Usage:
#   Step 1 — fetch manifest + samplesheet only (no files downloaded):
#     bash fetch_member_accessions.sh --member 2
#     bash fetch_member_accessions.sh --member 2 --accessions ENCSR000AKC,ENCSR000AKJ
#
#   Step 2 — same command with --download to also pull the FASTQ files:
#     bash fetch_member_accessions.sh --member 2 --download
#     bash fetch_member_accessions.sh --member 2 --accessions ENCSR000AKC,ENCSR000AKJ --download

set -euo pipefail

# ── defaults ──────────────────────────────────────────────────────────────────
MEMBER=""
CUSTOM_ACCESSIONS=""
DOWNLOAD=false
SAMPLESHEET_NAME="nfcore_chipseq_samplesheet.csv"
ORGANISM="Mus musculus"   # this is the mouse pipeline copy; override with --organism

# ── arg parsing ───────────────────────────────────────────────────────────────
usage() {
  echo "Usage: bash $(basename "$0") [--member <1-5|all>] [--accessions ACC1,ACC2,...] [--download] [--organism NAME] [--samplesheet-name NAME.csv]"
  echo ""
  echo "  --member       Optional. 1-5 to fetch one member's slice; 'all' or omitted"
  echo "                 to fetch the full released H3K27ac dataset for the organism."
  echo "  --accessions   Optional. Override with a specific comma-separated accession list."
  echo "  --download     Optional. Also download the FASTQ files (omit for manifest-only)."
  echo "  --organism     Optional. Organism scientific name. Default: ${ORGANISM}"
  echo "  --samplesheet-name Optional. Rename generated nf-core samplesheet to this CSV name."
  echo "                     Default: nfcore_chipseq_samplesheet.csv"
  exit 1
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --member)      MEMBER="$2";            shift 2 ;;
    --accessions)  CUSTOM_ACCESSIONS="$2"; shift 2 ;;
    --organism)    ORGANISM="$2";          shift 2 ;;
    --download)    DOWNLOAD=true;          shift   ;;
    --samplesheet-name) SAMPLESHEET_NAME="$2"; shift 2 ;;
    -h|--help)     usage ;;
    *) echo "Unknown option: $1"; usage ;;
  esac
done

# Default: no --member means "all" (union of every memberN.txt).
[[ -z "$MEMBER" ]] && MEMBER="all"

# Resolve script-relative paths (used for member list + later cd into raw/).
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# ── load accession list ──────────────────────────────────────────────────────
# Lists live in members/memberN.txt (one ENCSR ID per line). Generated by
# tools/compute_member_split.py, which keeps each member's ChIP assignments
# as-is and aligns the controls so every ChIP's matched controls live in the
# same member's file (no orphan controls, no missing controls).
if ! [[ "$MEMBER" =~ ^([1-5]|all)$ ]]; then
  echo "ERROR: --member must be 1-5 or 'all'."
  usage
fi

# MEMBER == "all" → no --accessions filter; encodefetch's search filters
# (assay-title + target-label + organism) match every released H3K27ac
# Histone ChIP-seq for the chosen organism (full dataset).
ACCESSIONS=""
if [[ "$MEMBER" != "all" ]]; then
  MEMBER_FILE="${SCRIPT_DIR}/members/member${MEMBER}.txt"
  [[ -f "$MEMBER_FILE" ]] || {
    echo "ERROR: $MEMBER_FILE not found."
    echo "       Run: python3 ${SCRIPT_DIR}/tools/compute_member_split.py"
    exit 1
  }
  ACCESSIONS="$MEMBER_FILE"
fi

# override with custom accessions if provided
if [[ -n "$CUSTOM_ACCESSIONS" ]]; then
  if [[ -f "$CUSTOM_ACCESSIONS" ]]; then
    # a file path (one accession per line). Resolve to an absolute path: the
    # script cd's into raw/ before running encodefetch, so a relative path
    # would no longer resolve and encodefetch would treat it as a literal
    # accession string (→ 404).
    ACCESSIONS="$(realpath "$CUSTOM_ACCESSIONS")"
  else
    # comma-separated string: write to temp file so the string length never
    # hits ENAMETOOLONG in encodefetch
    ACCESSIONS_TMP=$(mktemp /tmp/encodefetch_acc_XXXXXX.txt)
    trap 'rm -f "$ACCESSIONS_TMP"' EXIT
    echo "$CUSTOM_ACCESSIONS" | tr ',' '\n' > "$ACCESSIONS_TMP"
    ACCESSIONS="$ACCESSIONS_TMP"
  fi
fi

if [[ -z "$ACCESSIONS" ]]; then
  echo "Member ${MEMBER}: no --accessions filter (full released H3K27ac dataset)"
elif [[ -n "$CUSTOM_ACCESSIONS" ]]; then
  if [[ -f "$CUSTOM_ACCESSIONS" ]]; then
    COUNT=$(grep -c '^ENCSR' "$CUSTOM_ACCESSIONS")
  else
    COUNT=$(echo "$CUSTOM_ACCESSIONS" | tr ',' '\n' | wc -l)
  fi
  echo "Member ${MEMBER}: using custom accession list (${COUNT} accessions)"
else
  COUNT=$(grep -c '^ENCSR' "$MEMBER_FILE")
  echo "Member ${MEMBER}: using pre-assigned accession list (${COUNT} accessions)"
fi

if $DOWNLOAD; then
  echo "Mode: fetch manifest + samplesheet + download FASTQ files"
else
  echo "Mode: fetch manifest + samplesheet only  (re-run with --download to also pull FASTQ files)"
fi
echo "Samplesheet output name: ${SAMPLESHEET_NAME}"
echo ""

# ── run from the raw/ directory ────────────────────────────────────────────────
cd "${SCRIPT_DIR}/raw" || { echo "ERROR: could not cd into raw/"; exit 1; }

# encodefetch >= 0.5.0 downloads by default; --metadata-only skips downloads
# (the old --download flag no longer exists). So our $DOWNLOAD = false case
# is the one that needs an extra flag now.
DOWNLOAD_FLAG=""
if ! $DOWNLOAD; then
  DOWNLOAD_FLAG="--metadata-only"
fi

# When MEMBER=all (and no custom override), $ACCESSIONS is empty, so we omit
# --accessions entirely and let encodefetch's search filters return everything.
ACCESSIONS_FLAG=()
if [[ -n "$ACCESSIONS" ]]; then
  ACCESSIONS_FLAG=(--accessions "$ACCESSIONS")
fi

echo "Running command:"
echo "  encodefetch \\"
[[ -n "$ACCESSIONS" ]] && echo "    --accessions \"${ACCESSIONS}\" \\"
echo "    --assay-title \"Histone ChIP-seq\" \\"
echo "    --target-label H3K27ac \\"
echo "    --organism \"${ORGANISM}\" \\"
echo "    --file-type fastq \\"
echo "    --status released \\"
echo "    --threads 10 \\"
echo "    --control-strategy pool \\"
echo "    --progress \\"
echo "    --nfcore ${DOWNLOAD_FLAG}"
echo ""
echo "Please wait while it runs in the background..."

encodefetch \
  "${ACCESSIONS_FLAG[@]}" \
  --assay-title "Histone ChIP-seq" \
  --target-label H3K27ac \
  --organism "$ORGANISM" \
  --file-type fastq \
  --status released \
  --threads 10 \
  --control-strategy pool \
  --progress \
  --nfcore \
  ${DOWNLOAD_FLAG}

if [[ -n "$SAMPLESHEET_NAME" ]]; then
  if [[ "$SAMPLESHEET_NAME" == */* ]]; then
    DEST_SHEET="$SAMPLESHEET_NAME"
  else
    DEST_SHEET="encode_results/$SAMPLESHEET_NAME"
  fi

  # ENCODEfetch naming can vary by assay/version, so pick newest nf-core samplesheet.
  # Exclude destination path to avoid trying to move a file onto itself.
  mapfile -t NFCORE_SHEETS < <(ls -1t encode_results/nfcore*_samplesheet.csv 2>/dev/null | grep -Fxv "$DEST_SHEET" || true)

  if [[ ${#NFCORE_SHEETS[@]} -eq 0 ]]; then
    if [[ -f "$DEST_SHEET" ]]; then
      echo "Samplesheet already saved as: $DEST_SHEET"
      exit 0
    fi
    echo "WARNING: no nf-core samplesheet was found in raw/encode_results/."
    echo "         Looked for: raw/encode_results/nfcore*_samplesheet.csv"
    exit 1
  fi

  SRC_SHEET="${NFCORE_SHEETS[0]}"

  mkdir -p "$(dirname "$DEST_SHEET")"
  mv -f "$SRC_SHEET" "$DEST_SHEET"
  echo "Renamed samplesheet: $SRC_SHEET -> $DEST_SHEET"
fi
